const TRAVEL_BY_CODE = new Map(TRAVEL_COUNTRIES.map((country) => [country.code, country]));

export function countryByCode(code: string): TravelCountry | undefined {
  return TRAVEL_BY_CODE.get(code.trim().toUpperCase());
}

/** One to five country codes, in the order they were chosen. */
export function parseTravelWishlist(body: string): string[] | null {
  const parts = body
    .split(",")
    .map((part) => part.trim().toUpperCase())
    .filter(Boolean);
  if (parts.length < 1 || parts.length > TRAVEL_WISHLIST_MAX) return null;
  if (new Set(parts).size !== parts.length) return null;
  if (parts.some((code) => !TRAVEL_BY_CODE.has(code))) return null;
  return parts;
}

export function formatTravelWishlist(codes: readonly string[]): string {
  return codes.map((code) => code.toUpperCase()).join(",");
}

export function travelWishlistExportText(body: string): string {
  const codes = parseTravelWishlist(body);
  if (!codes) return body;
  return codes.map((code) => TRAVEL_BY_CODE.get(code)?.name ?? code).join(", ");
}

/** Flag emoji for a two-letter country code. */
export function countryFlagEmoji(code: string): string {
  const upper = code.trim().toUpperCase();
  if (!/^[A-Z]{2}$/.test(upper)) return "";
  return [...upper].map((char) => String.fromCodePoint(127397 + char.charCodeAt(0))).join("");
}
